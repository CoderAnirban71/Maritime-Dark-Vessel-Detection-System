// Helper to convert raw parsed AIS into Vessel and VesselTrack models
const parsedDemoTracks: VesselTrack[] = (rawEnnoreAis as any[]).map((v) => {
  const coordinates: [number, number][] = v.points.map((p: any) => [p.lat, p.lng]);
  const speeds = v.points.map((p: any) => p.speed);
  const minSpeed = Math.min(...speeds);
  const maxSpeed = Math.max(...speeds);
  const avgSpeed = Number((speeds.reduce((a: number, b: number) => a + b, 0) / (speeds.length || 1)).toFixed(1));

  return {
    mmsi: v.mmsi,
    vesselName: v.name,
    startTime: v.points[0]?.timestamp || '2017-01-27T12:00:35Z',
    endTime: v.points[v.points.length - 1]?.timestamp || '2017-01-28T11:59:05Z',
    pointsCount: v.points.length,
    coordinates,
    records: v.points.map((p: any, idx: number) => ({
      id: `${v.mmsi}-${idx}`,
      mmsi: v.mmsi,
      timestamp: p.timestamp,
      lat: p.lat,
      lng: p.lng,
      speedKnots: p.speed,
      headingDegrees: p.heading,
      courseOverGround: p.heading,
      navigationalStatus: p.speed < 0.5 ? 'At anchor' : 'Under way using engine',
      provenance: 'OBSERVED',
    })),
    minSpeedKnots: minSpeed,
    maxSpeedKnots: maxSpeed,
    avgSpeedKnots: avgSpeed,
    provenance: 'OBSERVED',
  };
});

